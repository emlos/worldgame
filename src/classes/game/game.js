// worldgame/src/game/game.js
import { World } from "../world/world.js";
import { Player } from "../player/player.js";
import { NPC } from "../npc/npc.js";
import { RandomStreams, deriveSeed, normalizeSeed, rollSeed } from "../../shared/util/random.js";
import { PLACE_TAGS } from "../../data/world/place.js";
import { NPC_REGISTRY } from "../../data/npc/npcs.js";
import { SaveValidationError, validateGameSave } from "./util/saveValidation.js";

export { SaveValidationError, validateGameSave };

const MS_PER_MINUTE = 60 * 1000;

// High-level orchestrator for world + player + NPCs.
export class Game {
    constructor({
        seed = rollSeed(),
        startDate = new Date(),
        playerOptions = {},
        npcTemplates = NPC_REGISTRY.filter((definition) => !definition.meta?.example),
    } = {}) {
        // --- deterministic random streams ---
        // `rnd` remains the general gameplay stream for callers that need one,
        // while engine subsystems use independent named streams.
        this.seed = normalizeSeed(seed);
        this.random = new RandomStreams(this.seed);
        this.rnd = this.getRNG("gameplay");

        // --- world ---
        this.world = new World({
            seed: deriveSeed(this.seed, "world"),
            startDate,
        });

        // --- player ---
        this.player = new Player(playerOptions);

        // --- story flags (separate from skills) ---
        this.flags = new Set();

        // --- npcs ---
        this.npcs = new Map();
        this._createNPCs(npcTemplates);
        this._initializeNPCBrains();

        // Player home (a Place instance generated by the map registry)
        const home = this._findFirstPlaceByKey("player_home");
        this.homeLocationId = home?.locationId ?? null;
        this.homePlaceId = home?.id ?? null;

        // Where is the player right now? Resolve location + place together so
        // we can never start "inside" a place belonging to another location.
        const hasStartLocation = playerOptions.startLocationId != null;
        const hasStartPlace = Object.prototype.hasOwnProperty.call(playerOptions, "startPlaceId");

        if (
            hasStartLocation &&
            playerOptions.startLocationId != null &&
            !this.world.locations.has(playerOptions.startLocationId)
        ) {
            throw new Error(`Unknown starting location: ${playerOptions.startLocationId}`);
        }

        this.currentLocationId = hasStartLocation
            ? playerOptions.startLocationId
            : (this.homeLocationId ?? this._pickDefaultLocationId());

        if (hasStartPlace) {
            // Explicit null means "start outside" and must not fall back home.
            this.currentPlaceId = playerOptions.startPlaceId;
        } else if (this.currentLocationId === this.homeLocationId) {
            this.currentPlaceId = this.homePlaceId;
        } else {
            this.currentPlaceId = null;
        }

        if (this.currentPlaceId != null) {
            const place = this._getPlaceById(this.currentLocationId, this.currentPlaceId);
            if (!place) {
                throw new Error(
                    `Unknown starting place '${this.currentPlaceId}' in location '${this.currentLocationId}'`,
                );
            }
            this.currentPlaceId = place.id;
            this.currentPlaceKey = place.key ?? null;
        } else {
            this.currentPlaceKey = null;
        }

        // Simple log of actions for debugging / history
        this.log = [];

        // simple event system for UI / other systems to subscribe
        this._listeners = {
            time: new Set(), // (game, minutes) => void
            timeJump: new Set(), // (game, { from, to, minutes, mode, source }) => void
            location: new Set(), // (game, newLocationId) => void
        };
    }

    // --------------------------
    // Basic getters
    // --------------------------
    get now() {
        return this.world.time.toDate();
    }

    get location() {
        return this.world.getLocation(this.currentLocationId);
    }

    get currentPlace() {
        if (!this.currentPlaceId) return null;
        const loc = this.location;
        return (loc?.places || []).find((p) => p.id === this.currentPlaceId) || null;
    }

    get npcsArray() {
        return [...this.npcs.values()];
    }

    /** Return a stable named RNG stream derived from this game's master seed. */
    getRNG(name = "gameplay") {
        return this.random.stream(name);
    }

    // --------------------------
    // Time & actions
    // --------------------------
    /**
     * Advance world time by N minutes and exactly simulate intervening NPC decisions.
     */
    advanceMinutes(mins) {
        const amount = Number(mins);
        if (!Number.isFinite(amount) || amount <= 0) {
            throw new TypeError(`Game.advanceMinutes requires positive minutes: ${String(mins)}`);
        }

        const target = new Date(this.now.getTime() + amount * MS_PER_MINUTE);
        return this._changeTimeTo(target, { mode: "simulate", source: "advance" });
    }

    /**
     * Move to an absolute timestamp. The default resync mode discards skipped NPC
     * micro-history and reconstructs a coherent destination state. Use
     * { mode: "simulate" } when every intervening decision must be processed.
     */
    jumpToDate(value, { mode = "resync" } = {}) {
        const target = value instanceof Date ? new Date(value.getTime()) : new Date(value);
        if (!Number.isFinite(target.getTime())) {
            throw new Error(`Invalid jump date: ${value}`);
        }
        if (mode !== "resync" && mode !== "simulate") {
            throw new Error(`Unknown time jump mode: ${mode}`);
        }

        return this._changeTimeTo(target, { mode, source: "jump" });
    }

    _changeTimeTo(target, { mode, source }) {
        const from = new Date(this.now.getTime());
        const to = new Date(target.getTime());
        const minutes = (to.getTime() - from.getTime()) / MS_PER_MINUTE;

        if (mode === "simulate" && minutes < 0) {
            throw new RangeError("Simulated time changes cannot run backwards; use resync mode");
        }
        if (mode === "simulate" && minutes === 0) {
            return { from, to, minutes, mode, source };
        }

        const snapshot = this._captureTimeRuntimeState();
        try {
            if (mode === "simulate") {
                this.world.advance(minutes);

                // Brains resolve meaningful decision boundaries, not every minute.
                for (const npc of this.npcs.values()) {
                    npc.brain?.updateTo(this.now, this);
                }
            } else {
                this.world.setDate(to);

                for (const npc of this.npcs.values()) {
                    npc.brain?.resyncAt(this.now, this);
                }
            }
        } catch (error) {
            this._restoreTimeRuntimeState(snapshot);
            throw error;
        }

        const change = { from, to: new Date(this.now.getTime()), minutes, mode, source };

        if (mode === "simulate") {
            // Normal time listeners are reserved for genuinely simulated elapsed time.
            for (const cb of this._listeners.time) cb(this, minutes, change);
        } else {
            // A resync is observational: skipped wages, encounters, deliveries, etc.
            // must not be inferred from the size of this delta.
            for (const cb of this._listeners.timeJump) cb(this, change);
        }

        return change;
    }

    _captureTimeRuntimeState() {
        return {
            date: new Date(this.now.getTime()),
            random: this.random.toJSON(),
            npcs: this.npcsArray.map((npc) => ({
                npc,
                locationId: npc.locationId,
                currentPlaceId: npc.currentPlaceId,
                brain: npc.brain?.toJSON?.() ?? null,
            })),
        };
    }

    _restoreTimeRuntimeState(snapshot) {
        this.world.setDate(snapshot.date);
        this.random.restoreJSON(snapshot.random);
        this.rnd = this.getRNG("gameplay");

        for (const state of snapshot.npcs) {
            state.npc.setLocationAndPlace(state.locationId, state.currentPlaceId);
            if (state.npc.brain && state.brain) state.npc.brain.restoreJSON(state.brain);
        }
    }

    /**
     * Move player to another location on the world map.
     */
    moveTo(locationId) {
        if (!this.world.locations.has(locationId)) {
            throw new Error(`Unknown location: ${locationId}`);
        }
        if (locationId === this.currentLocationId) return;

        this.currentLocationId = locationId;
        // When moving, you're typically not inside any specific place
        this.currentPlaceId = null;
        this.currentPlaceKey = null;

        // Subscribers should observe a fully consistent position.
        for (const cb of this._listeners.location) cb(this, locationId);

    }

    /**
     * Set where inside the location the player currently is.
     * Use a Place.id, or pass null and set currentPlaceKey to something virtual like "street".
     */
    setCurrentPlace({ placeId = null, placeKey = null } = {}) {
        if (placeId == null) {
            this.currentPlaceId = null;
            this.currentPlaceKey = placeKey == null ? null : String(placeKey);
            return;
        }

        const place = this._getPlaceById(this.currentLocationId, placeId);
        if (!place) {
            throw new Error(`Unknown place '${placeId}' in location '${this.currentLocationId}'`);
        }

        if (placeKey != null && String(placeKey) !== String(place.key ?? "")) {
            throw new Error(
                `Place key '${placeKey}' does not match place '${placeId}' (${place.key ?? "no key"})`,
            );
        }

        // Concrete places always use their canonical registry key. Virtual
        // place keys are represented only by { placeId: null, placeKey: ... }.
        this.currentPlaceId = place.id;
        this.currentPlaceKey = place.key ?? null;
    }

    // --- Story flags ---
    setFlag(flag, value = true) {
        const key = String(flag);
        if (value) this.flags.add(key);
        else this.flags.delete(key);
    }
    clearFlag(flag) {
        this.flags.delete(String(flag));
    }
    hasFlag(flag) {
        return this.flags.has(String(flag));
    }

    // --- Convenience queries ---
    getNPCsAtLocation(locationId = this.currentLocationId) {
        const id = String(locationId);
        return this.npcsArray.filter((n) => String(n.locationId) === id);
    }

    /**
     * Wrapper for player actions: do stuff, spend time, log it.
     * This is a good fit for your “choices” later.
     */
    runAction({ label, minutes = 0, apply }) {
        let amount = 0;
        if (minutes !== 0) {
            amount = Number(minutes);
            if (!Number.isFinite(amount) || amount <= 0) {
                throw new TypeError(`runAction requires positive minutes: ${String(minutes)}`);
            }
        }

        if (typeof label === "string" && label) {
            this.log.push({ t: this.now.toISOString(), label });
        }

        if (typeof apply === "function") {
            // let the action mutate game / player / npcs / world
            apply(this);
        }

        if (amount > 0) {
            this.advanceMinutes(amount);
        }
    }

    // --------------------------
    // Simple event/listener API
    // --------------------------
    /**
     * game.on("time", cb) -> unsubscribe function
     * game.on("timeJump", cb)
     * game.on("location", cb)
     */
    on(eventName, fn) {
        const set = this._listeners[eventName];
        if (!set) throw new Error(`Unknown event type: ${eventName}`);
        set.add(fn);
        return () => set.delete(fn);
    }

    // --------------------------
    // Save / load
    // --------------------------
    toJSON() {
        return {
            saveVersion: 6,
            seed: this.seed,
            random: this.random.toJSON(),
            time: this.now.toISOString(),
            world: this.world.toJSON(),
            player: this.player.toJSON(),
            npcs: this.npcsArray.map((npc) => npc.toJSON()),
            homeLocationId: this.homeLocationId,
            homePlaceId: this.homePlaceId,
            currentLocationId: this.currentLocationId,
            currentPlaceId: this.currentPlaceId,
            currentPlaceKey: this.currentPlaceKey,
            flags: [...this.flags],
            log: this.log.map((entry) => ({ ...entry })),
        };
    }

    static fromJSON(data, { traitResolver = null } = {}) {
        validateGameSave(data);

        const savedStartDate = data.world.time.date;

        // Construct only the runtime shell. Most constructor-generated state is
        // replaced below during hydration.
        const game = new Game({
            seed: data.seed,
            startDate: new Date(savedStartDate),
            playerOptions: {},
            npcTemplates: [],
        });

        game.random = RandomStreams.fromJSON(data.random);
        game.rnd = game.getRNG("gameplay");
        game.world = World.fromJSON(data.world);

        game.player = Player.fromJSON(data.player || {}, { traitResolver });

        game.npcs = new Map();
        for (const npcData of Array.isArray(data.npcs) ? data.npcs : []) {
            const npc = NPC.fromJSON(npcData, { traitResolver });
            const id = String(npc.id || npc.name);
            npc.id = id;
            game.npcs.set(id, npc);
        }

        game.homeLocationId = data.homeLocationId;
        game.homePlaceId = data.homePlaceId;
        game.currentLocationId = data.currentLocationId;
        game.currentPlaceId = data.currentPlaceId;
        game.currentPlaceKey = data.currentPlaceKey;
        game.flags = new Set(data.flags);
        game.log = data.log.map((entry) => ({ ...entry }));

        game._initializeNPCBrains();

        return game;
    }

    _initializeNPCBrains() {
        for (const npc of this.npcs.values()) {
            npc.brain?.initialize(this, this.now);
        }
    }

    _pickDefaultLocationId() {
        const first = this.world.locations.keys().next();
        return first.done ? null : first.value;
    }

    _findFirstPlaceByKey(placeKey) {
        const key = String(placeKey);
        for (const loc of this.world.locations.values()) {
            for (const p of loc.places || []) {
                if (p?.key === key) return p;
            }
        }
        return null;
    }

    _getPlaceKeyById(locationId, placeId) {
        const place = this._getPlaceById(locationId, placeId);
        return place?.key ?? null;
    }

    _getPlaceById(locationId, placeId) {
        if (placeId == null) return null;
        const loc = this.world.getLocation(locationId);
        return (loc?.places || []).find((p) => p.id === placeId) || null;
    }

    // --------------------------
    // Internals
    // --------------------------
    _createNPCs(templates) {
        for (const def of templates || []) {
            let npc;
            let id;

            if (def instanceof NPC) {
                npc = def;
                id = def.id || def.name;
            } else {
                npc = new NPC(def);
                id = def.id || npc.id || npc.name;
            }

            // Ensure id is always a string
            id = String(id || npc.name);
            npc.id = id;

            // Attach home + starting location
            this._assignHomeForNPC(id, npc);

            this.npcs.set(id, npc);
        }
    }

    /**
     * Assign a unique home Location + create a unique home Place for an NPC
     * based on npc.homePreference.
     *
     * homePreference supports selecting ONE strategy at random from:
     *  - withKey: pick random location that already contains any Place.key in the list
     *  - withPlaceCategory: pick location with the most places whose props.category matches any tag
     *  - withLocationCategory: pick location with the most location.tags matches
     *
     * nameFn(chosenLocation) is used to name the created home Place.
     */
    _assignHomeForNPC(id, npc) {
        const rnd = this.getRNG("npc-homes");
        const pref = npc?.homePreference;
        if (!pref) {
            throw new Error(`NPC '${id}' has no homePreference`);
        }

        const strategies = [];
        if (Array.isArray(pref.withKey) && pref.withKey.length) {
            strategies.push({ kind: "withKey", values: pref.withKey });
        }
        if (Array.isArray(pref.withPlaceCategory) && pref.withPlaceCategory.length) {
            strategies.push({ kind: "withPlaceCategory", values: pref.withPlaceCategory });
        }
        if (Array.isArray(pref.withLocationCategory) && pref.withLocationCategory.length) {
            strategies.push({ kind: "withLocationCategory", values: pref.withLocationCategory });
        }

        if (!strategies.length) {
            throw new Error(
                `homePreference for NPC '${id}' must include at least one of withKey, withPlaceCategory, withLocationCategory`,
            );
        }

        const pick = strategies[(rnd() * strategies.length) | 0];
        const allLocations = [...this.world.locations.values()];
        if (!allLocations.length) throw new Error("World has no locations");

        const pickRandom = (arr) => arr[(rnd() * arr.length) | 0];

        const placeHasAnyCategory = (place, wantedSet) => {
            const cat = place?.props?.category;
            if (!cat) return false;
            const cats = Array.isArray(cat) ? cat : [cat];
            for (const c of cats) if (wantedSet.has(c)) return true;
            return false;
        };

        let chosenLocation = null;

        if (pick.kind === "withKey") {
            const wantedKeys = new Set(pick.values.map(String));
            const candidates = allLocations.filter((loc) =>
                (loc.places || []).some((p) => wantedKeys.has(String(p.key))),
            );
            if (!candidates.length) {
                throw new Error(
                    `No location contains any place with key in [${[...wantedKeys].join(", ")}]`,
                );
            }
            chosenLocation = pickRandom(candidates);
        }

        if (pick.kind === "withPlaceCategory") {
            const wanted = new Set(pick.values);
            let bestScore = -1;
            let best = [];

            for (const loc of allLocations) {
                let score = 0;
                for (const pl of loc.places || []) {
                    if (placeHasAnyCategory(pl, wanted)) score++;
                }

                if (score > bestScore) {
                    bestScore = score;
                    best = [loc];
                } else if (score === bestScore) {
                    best.push(loc);
                }
            }

            if (bestScore <= 0) {
                throw new Error(
                    `No location has any places with category in [${[...wanted].join(", ")}]`,
                );
            }
            chosenLocation = pickRandom(best);
        }

        if (pick.kind === "withLocationCategory") {
            const wanted = new Set(pick.values);
            let bestScore = -1;
            let best = [];

            for (const loc of allLocations) {
                const tags = Array.isArray(loc.tags) ? loc.tags : [];
                let score = 0;
                for (const t of tags) if (wanted.has(t)) score++;

                if (score > bestScore) {
                    bestScore = score;
                    best = [loc];
                } else if (score === bestScore) {
                    best.push(loc);
                }
            }

            if (bestScore <= 0) {
                throw new Error(`No location has any tags in [${[...wanted].join(", ")}]`);
            }
            chosenLocation = pickRandom(best);
        }

        if (!chosenLocation) {
            throw new Error(`Failed to choose a home location for NPC '${id}'`);
        }

        // Create a unique home Place at the chosen location
        const homeId = `home_${id}`;
        const displayName =
            typeof pref.nameFn === "function" ? pref.nameFn(chosenLocation) : `${npc.name}'s home`;

        const homePlace = this.world.createPlaceAt(
            {
                id: homeId,
                key: homeId,
                name: displayName,
                props: {
                    category: [PLACE_TAGS.housing],
                    ownerNpcId: id,
                    isResidence: true,
                    discovered: false,
                    icon: "🏠",
                },
            },
            chosenLocation.id,
        );

        npc.homeLocationId = String(chosenLocation.id);
        npc.homePlaceId = homePlace ? homePlace.id : homeId;

        // Start NPC at home by default
        if (!npc.locationId) {
            npc.setLocationAndPlace(String(chosenLocation.id), npc.homePlaceId);
        }
    }
}
